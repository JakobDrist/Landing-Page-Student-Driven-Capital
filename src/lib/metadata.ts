import type { Metadata } from "next";
import routes from "@/content/routes.json";
import { home } from "@/content/data";

export const siteName = "DSD Invest";
export const siteLabel = "Studenterdrevet investeringsorganisation";
export const siteTitle = `${siteName} | ${siteLabel}`;
/** The homepage hero's description doubles as the site description. */
export const siteDescription = home.hero.description;

/**
 * Absolute base for link-preview URLs: the production domain on Vercel, the
 * deployment URL on previews, localhost in development.
 */
const siteUrl = process.env.VERCEL_PROJECT_PRODUCTION_URL
  ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}`
  : process.env.VERCEL_URL
    ? `https://${process.env.VERCEL_URL}`
    : "http://localhost:3000";

/** Link-preview image generated by `src/app/opengraph-image.tsx`. */
const previewImage = {
  url: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: `${siteName} – ${home.hero.title}`,
};

/** Shared link-preview fields; pages override the title. */
const openGraph = {
  siteName,
  locale: "da_DK",
  type: "website",
  description: siteDescription,
  images: [previewImage],
} satisfies Metadata["openGraph"];

export const rootMetadata: Metadata = {
  metadataBase: new URL(siteUrl),
  title: siteTitle,
  description: siteDescription,
  applicationName: siteName,
  openGraph: { ...openGraph, title: siteTitle, url: "/" },
  twitter: {
    card: "summary_large_image",
    title: siteTitle,
    description: siteDescription,
    images: [previewImage],
  },
};

export function pageMetadata(pathname: string): Metadata {
  const title =
    routes.find((route) => route.path === pathname)?.metadataTitle ?? siteTitle;
  return {
    title,
    description: siteDescription,
    openGraph: { ...openGraph, title, url: pathname },
    twitter: {
      card: "summary_large_image",
      title,
      description: siteDescription,
      images: [previewImage],
    },
  };
}
